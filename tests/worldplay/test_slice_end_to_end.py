"""The playable slice end to end, with the mock model: an automated mirror
of the owner's acceptance test 3 (a lost eye the AI sees only in scenes set
after its date), plus save and reload, the "World" instruction, continuing
a scene from its history, and no extra model calls during turns.

A dated fact reaches the AI two ways: through prose regenerated for the
scene's stretch of time (the eye, written at creation for 314 on), or,
when a stretch's prose predates a fact, through a since line (the scar,
added by an edit after the prose was written).

Everything runs through the real code; only `MockClient` responses are
queued. One `MockClient` serves every agent and every world call, so its
`prompt_history` is the whole run's record of model calls, by `kind`.

The `@` action's path is `ConversationAgent.converse(actor, instruction=...)`.
"""

import json
from collections import Counter

import pytest

import talemate.instance as instance
from talemate.config import Config, get_config
from talemate.config.schema import RecentScenes
from talemate.context import ActiveScene
from talemate.load import load_scene
from talemate.tale_mate import Scene
from talemate.world.dates import WorldDate
from talemate.world.store import Source
from talemate.worldplay.create import accept_preview, preview_thing
from talemate.worldplay.persistence import (
    close_world_scene,
    save_world_scene,
    world_target,
)
from talemate.worldplay.setup import continue_setup, plan_scene, start_scene

from conftest import (
    MockClient,
    MockClientContext,
    MockMemoryAgent,
    MockScene,
    bootstrap_scene,
    client_responses,
)

EYE_FACT = "Lost her left eye to a smuggler's hook."

CREATE_REPLY = json.dumps(
    {
        "name": "Maren",
        "facts": [
            {"category": "appearance", "text": "Wears a salt-stained ferryman's coat."},
            {"category": "appearance", "text": EYE_FACT, "since": "314"},
            {"category": "background", "text": "Pilots the ferry at Veldhaer."},
            {"category": "personality", "text": "Wry and patient."},
        ],
    }
)

# the preview's prose is written from every fact: how Maren reads at the
# open, "now" end of her timeline, from 314 on
PROSE_NOW = (
    "Maren is the Veldhaer ferry pilot, in a salt-stained coat; "
    "she lost her left eye to a smuggler's hook."
)
PERSONALITY = "Maren is wry and patient."
# regenerated by scene A's start, from her facts at 313
PROSE_313 = "Maren is the Veldhaer ferry pilot, in a salt-stained coat."

# added by a fact edit after creation
SCAR_FACT = "A scar across her cheek."
# regenerated by scene B's start, for 315, from her facts then
PROSE_315 = (
    "Maren is the Veldhaer ferry pilot, in a salt-stained coat; she lost "
    "her left eye to a smuggler's hook, and a scar crosses her cheek."
)

SETUP_A = {
    "player": "Ilse",
    "characters": [
        {"name": "Ilse", "facts": ["A young deckhand."]},
        {"name": "Maren"},
    ],
    "place": {"name": "The Drowned Stag"},
    "goal": "Hire Maren's ferry before the flood.",
    "intro": "Rain drums on the tavern roof.",
}

VAULT_FACT = "A flooded dungeon under the weir."
SETUP_B = {
    "player": "Ilse",
    "characters": [
        {"name": "Ilse", "facts": ["A young deckhand."]},
        {"name": "Maren"},
    ],
    "place": {"name": "The Sunken Vault", "facts": [VAULT_FACT]},
    "goal": "Find the smuggler's hoard.",
    "intro": "Water drips from the vault's ceiling.",
}

CONTINUE_REPLY = json.dumps(
    {
        "player": "Ilse",
        "characters": [{"name": "Maren"}],
        "place": {"name": "The Sunken Vault"},
        "goal": "Get the hoard out before the tide.",
        "intro": "The tide is rising.",
    }
)

TURN_A = "Maren: The ferry leaves at dawn, if the river lets it."
TURN_A2 = "Maren: A year on, and the river still floods."
TURN_B = "Maren: Mind the steps. The vault floods twice a day."
TURN_B2 = "Maren: There. Behind the third pillar."
SUMMARY = "Ilse and Maren searched the vault and found the hoard."


def _queue(*responses: str) -> None:
    for response in responses:
        client_responses.get().append(response)


async def _noop(self, *args, **kwargs):
    pass


@pytest.fixture
def loadable(monkeypatch):
    """What loading a world scene needs from a test: no memory database,
    an empty recent-scenes list and no config broadcast (as in
    test_setup.py)."""

    monkeypatch.setattr(MockMemoryAgent, "set_db", _noop)
    monkeypatch.setattr(MockMemoryAgent, "_get_document", lambda self, id: {})
    monkeypatch.setattr(Scene, "commit_to_memory", _noop)
    monkeypatch.setattr(Config, "set_dirty", _noop)
    monkeypatch.setattr(get_config(), "recent_scenes", RecentScenes(scenes=[]))


async def _load(world, scene_id: str, client: MockClient) -> Scene:
    """Load a world scene through `load_scene` and its `world://` target,
    with every agent on the run's one `client`. Long-term memory is off:
    the mock memory agent has no backend to search (as in the golden
    scene test)."""

    scene = MockScene()
    bootstrap_scene(scene)
    for agent in instance.AGENTS.values():
        agent.client = client
        long_term_memory = getattr(agent, "actions", {}).get("use_long_term_memory")
        if long_term_memory is not None:
            long_term_memory.enabled = False
    scene.mock_client = client
    return await load_scene(scene, world_target(str(world.path), scene_id))


async def _turn(scene: Scene, client: MockClient, name: str, reply: str) -> str:
    """One `@` action turn for `name`: queue the reply, converse with an
    instruction, push the messages. Returns the conversation prompt sent,
    after checking it was the turn's only model call."""

    actor = next(a for a in scene.actors if a.character.name == name)
    before = len(client.prompt_history)
    with ActiveScene(scene):
        async with MockClientContext():
            _queue(reply)
            messages = await instance.get_agent("conversation").converse(
                actor, instruction="Maren answers Ilse."
            )
            await scene.push_history(messages)

    calls = client.prompt_history[before:]
    assert [call["kind"] for call in calls] == ["conversation"]
    return str(calls[0]["prompt"])


async def test_slice_end_to_end(world, loadable):
    client = MockClient("slice")
    world.set_present(WorldDate.of(316))
    with world.revision(Source.manual(note="setup")) as rev:
        stag = rev.create_thing("place", fields={"name": "The Drowned Stag"})
        rev.add_fact(stag, "description", "A tavern with water on its floor.")

    # 1. create Maren from a prompt, with a lost eye from 314
    async with MockClientContext():
        _queue(CREATE_REPLY)
        preview = await preview_thing(
            world,
            "character",
            "a one-eyed ferry pilot",
            {"name": "Maren", "born": WorldDate.of(290)},
            client,
        )
    eye = next(f for f in preview.facts if f.text == EYE_FACT)
    assert eye.since == WorldDate.of(314)
    maren = accept_preview(world, preview)

    # the owner then adds a scar from 314, the way the World tab's
    # `add_fact` writes it; with no AI client its background prose update
    # is skipped, so the prose cached for 314 on goes stale
    with world.revision(Source.manual()) as rev:
        rev.add_fact(maren, "appearance", SCAR_FACT, valid_from=WorldDate.of(314))

    # 2. scene A at 313, at a world place: the AI never sees the eye
    setup_a = await plan_scene(
        world,
        "Ilse hires Maren at the Drowned Stag",
        {},
        None,
        WorldDate.of(313),
        None,
        reply=SETUP_A,
    )
    async with MockClientContext():
        # 313 is before the cached stretch: both sections are written fresh
        _queue(PROSE_313, PERSONALITY)
        scene_a_id = await start_scene(world, setup_a, client)

    scene_a = await _load(world, scene_a_id, client)
    try:
        assert scene_a.get_player_character().name == "Ilse"
        prompt_a = await _turn(scene_a, client, "Maren", TURN_A)

        # a year passes in scene A, into 314: the turn after it sees the
        # scar through a since line (its stretch's prose predates the
        # scar) and the eye through that prose, with no model call for
        # the time passage or mid-turn
        before = len(client.prompt_history)
        with ActiveScene(scene_a):
            await instance.get_agent("world_state").advance_time("P1Y")
        assert client.prompt_history[before:] == []
        prompt_a2 = await _turn(scene_a, client, "Maren", TURN_A2)
    finally:
        close_world_scene(scene_a)

    assert PROSE_313 in prompt_a
    assert "left eye" not in prompt_a
    assert "Since 314" not in prompt_a
    # the World instruction: the goal and the world place, with its facts
    assert "Hire Maren's ferry before the flood." in prompt_a
    assert "The Drowned Stag" in prompt_a
    assert "A tavern with water on its floor." in prompt_a
    assert SCAR_FACT not in prompt_a

    assert f"Since 314: {SCAR_FACT}" in prompt_a2
    assert "she lost her left eye to a smuggler's hook" in prompt_a2
    assert "Hire Maren's ferry before the flood." in prompt_a2

    # 3. scene B at 315, at an invented place: the AI sees the eye
    setup_b = await plan_scene(
        world,
        "Ilse and Maren search the Sunken Vault",
        {"Maren": maren},
        None,
        WorldDate.of(315),
        None,
        reply=SETUP_B,
    )
    before = len(client.prompt_history)
    async with MockClientContext():
        # the prose for 314 on is stale (the scar): both sections rewritten
        _queue(PROSE_315, PERSONALITY)
        scene_b_id = await start_scene(world, setup_b, client)
    assert [c["kind"] for c in client.prompt_history[before:]] == ["analyze"] * 2

    scene_b = await _load(world, scene_b_id, client)
    try:
        prompt_b = await _turn(scene_b, client, "Maren", TURN_B)
        save_world_scene(scene_b)
    finally:
        close_world_scene(scene_b)

    assert PROSE_315 in prompt_b
    # fresh prose: no since lines
    assert "Since 314" not in prompt_b
    assert "Find the smuggler's hoard." in prompt_b
    assert "The Sunken Vault" in prompt_b
    assert VAULT_FACT in prompt_b

    # 4. reload B and play on: the World instruction is still there
    scene_b = await _load(world, scene_b_id, client)
    try:
        assert TURN_B in [str(m) for m in scene_b.history][-1]
        prompt_b2 = await _turn(scene_b, client, "Maren", TURN_B2)
        assert PROSE_315 in prompt_b2
        assert "Find the smuggler's hoard." in prompt_b2
        assert "The Sunken Vault" in prompt_b2
        assert VAULT_FACT in prompt_b2

        # time passes in B; no model call for that either
        before = len(client.prompt_history)
        with ActiveScene(scene_b):
            await instance.get_agent("world_state").advance_time("P2D")
        assert client.prompt_history[before:] == []

        # 5. continue B in a new scene, from its history, the way the
        # router's `continue_scene` does it: save the loaded scene first,
        # then plan with the scene loaded (the summarizer's scene)
        save_world_scene(scene_b)
        before = len(client.prompt_history)
        with ActiveScene(scene_b):
            async with MockClientContext():
                _queue(SUMMARY, CONTINUE_REPLY)
                setup_c = await continue_setup(
                    world, scene_b_id, "They get the hoard out", client
                )
    finally:
        close_world_scene(scene_b)

    summarized, planned = client.prompt_history[before:]
    assert summarized["kind"] == "summarize_2048"
    assert "The vault floods twice a day." in str(summarized["prompt"])
    assert "Behind the third pillar." in str(summarized["prompt"])
    assert setup_c.summary == SUMMARY
    assert SUMMARY in str(planned["prompt"])

    record_b = world.scenes().get(scene_b_id)
    last_elapsed = world.scenes().messages(scene_b_id)[-1].elapsed
    assert last_elapsed == "P2D"
    async with MockClientContext():
        scene_c_id = await start_scene(world, setup_c, client)
    record_c = world.scenes().get(scene_c_id)
    assert record_c.start == record_b.start.plus(last_elapsed)
    assert record_c.continued_from == scene_b_id

    # 6. the whole run's model calls, by kind: three turns, and the rest
    # only at creation, scene setup and continuing
    kinds = Counter(call["kind"] for call in client.prompt_history)
    assert kinds == {
        "creative_instruction_3072": 1,  # create Maren
        "creative_instruction_2048": 1,  # plan the continue
        # Maren's prose: at creation, at 313 for scene A, at 315 for B
        "analyze": 6,
        "conversation": 4,  # the turns
        "summarize_2048": 1,  # scene B's summary, for the continue
    }
